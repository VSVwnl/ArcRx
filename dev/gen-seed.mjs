// Generates migrations/002-seed-demo.sql deterministically so the dashboards
// have six weeks of believable longitudinal data on first run.
import { writeFileSync } from 'node:fs';

let seed = 20261107;
const rand = () => {
  seed = (seed * 1664525 + 1013904223) % 4294967296;
  return seed / 4294967296;
};
const jitter = (amt) => (rand() - 0.5) * 2 * amt;
const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;

const TODAY = new Date('2026-11-07T09:00:00-05:00');
const day = (d, hour = 9) => {
  const t = new Date(TODAY);
  t.setDate(t.getDate() - d);
  t.setHours(hour, Math.floor(rand() * 50), 0, 0);
  return t;
};
const iso = (t) => t.toISOString();

const EXERCISE_FLAGS = {
  shoulder_abduction: ['trunk_lean', 'shoulder_hike'],
  elbow_flexion: ['shoulder_drift', 'trunk_lean'],
  neck_rotation: ['head_tilt', 'chin_drop'],
  neck_lateral_flexion: ['head_rotation', 'chin_drop'],
};

const patients = [
  {
    id: 1, username: 'maya.chen', mrn: 'ARX-1041', name: 'Maya Chen',
    condition: 'Rotator cuff repair (R), post-op week 6', surgery: '2026-09-22', clinician: 'dr.okafor',
    plan: { id: 1, key: 'shoulder_abduction', side: 'right', target: 150, sets: 3, reps: 10, freq: 5, pain: 5 },
    // rises 58 → 118 over 4.5 weeks, then plateaus at ~118-122
    curve: (d) => (d > 12 ? 58 + (42 - d) * 2.0 : 118 + jitter(2.5)),
    comp: (d) => (d > 12 ? 22 - (42 - d) * 0.5 : 12),
    pain: () => (rand() < 0.3 ? 3 : 2),
    perWeek: 4.6, days: 42,
  },
  {
    id: 2, username: 'darnell.reed', mrn: 'ARX-1077', name: 'Darnell Reed',
    condition: 'Distal humerus ORIF (L), post-op week 5', surgery: '2026-10-01', clinician: 'dr.okafor',
    plan: { id: 2, key: 'elbow_flexion', side: 'left', target: 130, sets: 3, reps: 12, freq: 5, pain: 5 },
    curve: (d) => 72 + (35 - d) * 1.6 + jitter(2),
    comp: (d) => clamp(18 - (35 - d) * 0.4, 4, 30),
    pain: () => (rand() < 0.2 ? 2 : 1),
    perWeek: 4.8, days: 35,
  },
  {
    id: 3, username: 'priya.natarajan', mrn: 'ARX-1102', name: 'Priya Natarajan',
    condition: 'Cervical radiculopathy C5–C6, conservative', surgery: null, clinician: 'dr.okafor',
    plan: { id: 3, key: 'neck_rotation', side: 'right', target: 70, sets: 2, reps: 8, freq: 6, pain: 5 },
    // improves 36 → 62, then regresses over the last week with pain
    curve: (d) => (d > 6 ? 36 + (30 - d) * 1.1 + jitter(1.5) : 50 - (6 - d) * 1.2 + jitter(1.5)),
    comp: (d) => (d > 6 ? 14 : 34 + (6 - d) * 4),
    pain: (d) => (d > 6 ? 2 : 4 + Math.round((6 - d) / 3)),
    perWeek: 5.5, days: 30,
  },
  {
    id: 4, username: 'tomas.alvarez', mrn: 'ARX-1118', name: 'Tomás Alvarez',
    condition: 'Adhesive capsulitis (L), stage 2', surgery: null, clinician: 'dr.okafor',
    plan: { id: 4, key: 'shoulder_abduction', side: 'left', target: 120, sets: 3, reps: 8, freq: 5, pain: 5 },
    // decent progress, then stopped practising 9 days ago
    curve: (d) => 64 + (28 - d) * 1.0 + jitter(2),
    comp: () => 20 + jitter(6),
    pain: () => 3,
    perWeek: 4.2, days: 28, stopAt: 9,
  },
];

const lines = [];
lines.push('-- Demo seed (generated by dev/gen-seed.mjs). Safe to re-run: every insert is ON CONFLICT DO NOTHING.');
for (const p of patients) {
  lines.push(`INSERT INTO patients (id, username, mrn, name, condition, surgery_date, clinician) VALUES (${p.id}, ${q(p.username)}, ${q(p.mrn)}, ${q(p.name)}, ${q(p.condition)}, ${p.surgery ? q(p.surgery) : 'NULL'}, ${q(p.clinician)}) ON CONFLICT (id) DO NOTHING;`);
  const pl = p.plan;
  lines.push(`INSERT INTO exercise_plans (id, patient_id, exercise_key, side, target_rom, sets, reps, frequency_per_week, pain_threshold) VALUES (${pl.id}, ${p.id}, ${q(pl.key)}, ${q(pl.side)}, ${pl.target}, ${pl.sets}, ${pl.reps}, ${pl.freq}, ${pl.pain}) ON CONFLICT (id) DO NOTHING;`);
}

let sessionId = 100;
let repId = 1000;
const noteRows = [];
for (const p of patients) {
  for (let d = p.days; d >= 1; d--) {
    if (p.stopAt && d <= p.stopAt) continue;
    if (rand() > p.perWeek / 7) continue;
    const start = day(d, 8 + Math.floor(rand() * 10));
    const peak = clamp(p.curve(d), 10, 179);
    const reps = p.plan.reps + Math.round(jitter(1.4));
    const comp = clamp(p.comp(d) + jitter(5), 0, 100);
    const pain = clamp(p.pain(d), 0, 10);
    const smooth = clamp(68 + (p.days - d) * 0.5 + jitter(6) - comp * 0.15, 30, 98);
    const repPeaks = Array.from({ length: reps }, (_, i) =>
      clamp(peak - 2 - rand() * 7 + (i === Math.floor(reps / 2) ? 2 + rand() * 7 : 0), 5, 179),
    );
    const meanRom = repPeaks.reduce((a, b) => a + b, 0) / reps;
    const end = new Date(start.getTime() + reps * 4200 + 20000);
    sessionId += 1;
    lines.push(`INSERT INTO sessions (id, patient_id, plan_id, exercise_key, side, started_at, ended_at, reps, peak_rom, mean_rom, smoothness, compensation_pct, pain_score, source) VALUES (${sessionId}, ${p.id}, ${p.plan.id}, ${q(p.plan.key)}, ${q(p.plan.side)}, ${q(iso(start))}, ${q(iso(end))}, ${reps}, ${Math.max(...repPeaks).toFixed(1)}, ${meanRom.toFixed(1)}, ${smooth.toFixed(1)}, ${comp.toFixed(1)}, ${pain}, 'webcam') ON CONFLICT (id) DO NOTHING;`);
    const flaggedCount = Math.round((comp / 100) * reps);
    repPeaks.forEach((pk, i) => {
      repId += 1;
      const flags = i < flaggedCount ? [EXERCISE_FLAGS[p.plan.key][i % 2]] : [];
      lines.push(`INSERT INTO reps (id, session_id, rep_index, peak_angle, duration_ms, hold_ms, smoothness, compensation_flags) VALUES (${repId}, ${sessionId}, ${i + 1}, ${pk.toFixed(1)}, ${Math.round(3200 + jitter(900))}, ${Math.round(600 + jitter(400))}, ${clamp(smooth + jitter(8), 20, 99).toFixed(1)}, ${q(JSON.stringify(flags))}::jsonb) ON CONFLICT (id) DO NOTHING;`);
    });
    if (d === 14 || d === 28) noteRows.push({ p, sessionId, start, peak, reps, comp, smooth });
  }
}

let noteId = 1;
for (const n of noteRows) {
  noteId += 1;
  const note = `Objective: ${n.p.plan.key.replace('_', ' ')} ${n.p.plan.side}, peak ${n.peak.toFixed(0)}° vs target ${n.p.plan.target}°, ${n.reps} reps, smoothness ${n.smooth.toFixed(0)}/100, compensation ${n.comp.toFixed(0)}% of reps. Assessment: progressing as expected. Plan: continue current prescription.`;
  lines.push(`INSERT INTO progress_notes (id, patient_id, session_id, author, note, metrics, created_at) VALUES (${noteId}, ${n.p.id}, ${n.sessionId}, 'dr.okafor', ${q(note)}, ${q(JSON.stringify({ peak_rom: Number(n.peak.toFixed(1)), reps: n.reps }))}::jsonb, ${q(iso(n.start))}) ON CONFLICT (id) DO NOTHING;`);
}
// A resolved historical alert so the alert list shows the lifecycle
lines.push(`INSERT INTO alerts (id, patient_id, session_id, severity, kind, title, body, status, created_by, created_at, acknowledged_at) VALUES (1, 1, 101, 'medium', 'compensation', 'Shoulder hike on 38% of reps', 'Early sessions showed consistent scapular elevation during abduction; re-cued at visit.', 'resolved', 'agent:rehab_triage', ${q(iso(day(36)))}, ${q(iso(day(35)))}) ON CONFLICT (id) DO NOTHING;`);

// Dates above are anchored to the day the seed was authored. Shift them so the data always
// ends "yesterday" relative to the day the migration runs (a fresh workspace or deploy),
// keeping the plateau / regression / ready / non-adherent trajectories true over time.
const SHIFT = `(CURRENT_DATE - DATE '${TODAY.toISOString().slice(0, 10)}') * INTERVAL '1 day'`;
lines.push(`UPDATE sessions SET started_at = started_at + ${SHIFT}, ended_at = ended_at + ${SHIFT};`);
lines.push(`UPDATE progress_notes SET created_at = created_at + ${SHIFT};`);
lines.push(`UPDATE alerts SET created_at = created_at + ${SHIFT}, acknowledged_at = acknowledged_at + ${SHIFT};`);
lines.push(`UPDATE patients SET surgery_date = surgery_date + (CURRENT_DATE - DATE '${TODAY.toISOString().slice(0, 10)}') WHERE surgery_date IS NOT NULL;`);

// What the triage agent would already have done for the regression case (Priya, id 3): an open
// high-severity alert and an objective note, derived from her latest seeded session so the
// clinic queue and chart have agent output before anyone runs a live session.
lines.push(`INSERT INTO alerts (id, patient_id, session_id, severity, kind, title, body, status, created_by, created_at)
SELECT 2, s.patient_id, s.id, 'high', 'regression',
  'Peak ROM regressed to ' || ROUND(s.peak_rom) || '° (' || ROUND(s.peak_rom / ep.target_rom * 100) || '% of target)',
  'Trajectory assessment flagged regression; latest pain ' || s.pain_score || '/10. Suggested: clinician review within 48h; hold progression; confirm a pain-free arc before the next session.',
  'open', 'agent:rehab_triage', s.ended_at + INTERVAL '20 seconds'
FROM sessions s JOIN exercise_plans ep ON ep.patient_id = s.patient_id AND ep.active = TRUE
WHERE s.patient_id = 3 ORDER BY s.started_at DESC LIMIT 1
ON CONFLICT (id) DO NOTHING;`);
lines.push(`INSERT INTO progress_notes (id, patient_id, session_id, author, note, metrics, created_at)
SELECT (SELECT COALESCE(MAX(id), 0) + 1 FROM progress_notes), s.patient_id, s.id, 'agent:rehab_triage',
  'Objective: ' || ROUND(s.peak_rom) || '° peak vs target ' || ROUND(ep.target_rom) || '°, ' || s.reps || ' reps, smoothness ' || ROUND(s.smoothness) || '/100, compensation ' || ROUND(s.compensation_pct) || '% of reps, pain ' || s.pain_score || '/10. Assessment: regression. Plan: hold progression; clinician review within 48h.',
  jsonb_build_object('peak_rom', s.peak_rom, 'reps', s.reps, 'pain', s.pain_score),
  s.ended_at + INTERVAL '25 seconds'
FROM sessions s JOIN exercise_plans ep ON ep.patient_id = s.patient_id AND ep.active = TRUE
WHERE s.patient_id = 3 ORDER BY s.started_at DESC LIMIT 1;`);

for (const t of ['patients', 'exercise_plans', 'sessions', 'reps', 'progress_notes', 'alerts']) {
  lines.push(`SELECT setval('${t}_id_seq', (SELECT MAX(id) FROM ${t}));`);
}

writeFileSync('migrations/002-seed-demo.sql', lines.join('\n') + '\n');
console.log(`wrote migrations/002-seed-demo.sql: ${sessionId - 100} sessions, ${repId - 1000} reps`);
